#!/usr/bin/env node
// Writes res/drawable/ic_*.xml vector drawables from @mdi/js path data (Material Design Icons, Apache 2.0).
// Usage: npm install --no-save @mdi/js && node tools/icons.mjs [path/to/@mdi/js/mdi.js]
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = process.argv[2] ?? join(root, 'node_modules', '@mdi', 'js', 'mdi.js');
const mdi = await import(pathToFileURL(source).href);

// drawable name → MDI export
const ICONS = {
  ic_home: 'mdiHomeOutline',
  ic_settings: 'mdiCogOutline',
  ic_tune: 'mdiTuneVariant',
  ic_apps: 'mdiViewGridOutline',
  ic_star: 'mdiStar',
  ic_star_outline: 'mdiStarOutline',
  ic_chevron: 'mdiChevronRight',
  ic_chevron_left: 'mdiChevronLeft',
  ic_check: 'mdiCheckCircleOutline',
  ic_alert: 'mdiAlertCircleOutline',
  ic_tv: 'mdiTelevision',
  ic_remote: 'mdiRemoteTv',
  ic_shield: 'mdiVideoInputHdmi',
  ic_server: 'mdiHomeAssistant',
  ic_permission: 'mdiGestureTapButton',
  ic_picture: 'mdiPaletteOutline',
  ic_brightness: 'mdiBrightness6',
  ic_leaf: 'mdiLeaf',
  ic_sound: 'mdiSurroundSound',
  ic_sleep: 'mdiSleep',
  ic_logo: 'mdiWatermark',
  ic_power: 'mdiPowerStandby',
  ic_input: 'mdiVideoSwitchOutline',
};

mkdirSync(join(root, 'res', 'drawable'), { recursive: true });
for (const [name, key] of Object.entries(ICONS)) {
  const path = mdi[key];
  if (!path) throw new Error(`Unknown MDI icon ${key}`);
  writeFileSync(join(root, 'res', 'drawable', `${name}.xml`),
    `<!-- ${key} from Material Design Icons (Apache 2.0), generated by tools/icons.mjs -->\n` +
    `<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" ` +
    `android:viewportWidth="24" android:viewportHeight="24">\n` +
    `    <path android:fillColor="#FFFFFFFF" android:pathData="${path}" />\n</vector>\n`);
}
console.log(`${Object.keys(ICONS).length} icons written`);
